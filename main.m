function C = create_matrix(alpha, h, n)
  % alpha - параметр регуляризации
  % h - шаг сетки
  % n - размер матрицы (количество узлов)

  % Инициализируем матрицу нулями
  C = zeros(n, n);

  % ===== Внутренние узлы (со 2 по n-1) =====
  for i = 2:n-1
      C(i, i-1) = -alpha / h^2;
      C(i, i)   = alpha * (1 + 2/h^2);
      C(i, i+1) = -alpha / h^2;
  end

  % ===== Первая строка: условие z'(a)=0 (первый порядок) =====
  C(1, 1) =  1;
  C(1, 2) = -1;
  % Остальные элементы первой строки = 0

  % ===== Последняя строка: условие z'(b)=0 =====
  C(n, n-1) = -1;
  C(n, n)   =  1;
endfunction
